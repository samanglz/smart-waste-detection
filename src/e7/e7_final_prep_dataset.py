def yolo_to_xyxy(box, w, h):
    cx, cy, bw, bh = box
    x1 = int((cx - bw/2) * w)
    y1 = int((cy - bh/2) * h)
    x2 = int((cx + bw/2) * w)
    y2 = int((cy + bh/2) * h)
    return x1, y1, x2, y2


def load_labels(label_path):
    labels = []
    for line in label_path.read_text().strip().splitlines():
        cls, cx, cy, bw, bh = map(float, line.split())
        labels.append((int(cls), (cx, cy, bw, bh)))
    return labels


def is_train_background(img_path, labels, threshold=3):
    stem = img_path.stem.split("_e7_")[0]
    orig_path = ORIG_IMG / f"{stem}.jpg"

    if not orig_path.exists():
        return False

    syn = cv2.imread(str(img_path))
    ori = cv2.imread(str(orig_path))

    if syn is None or ori is None:
        return False

    h, w = syn.shape[:2]

    # آخرین لیبل = آبجکت جدید
    _, box = labels[-1]
    x1, y1, x2, y2 = yolo_to_xyxy(box, w, h)

    mask = np.ones((h, w), np.uint8)
    mask[max(0,y1):min(h,y2), max(0,x1):min(w,x2)] = 0

    diff = np.abs(syn.astype(np.int16)-ori.astype(np.int16))
    mad = diff[mask==1].mean()

    return mad < threshold


